/** Creates the single ordered production fixed-step pipeline. */
export function createProductionSimulationSystems(compiledAssembly = null) {
  const flexibleLines = Boolean(compiledAssembly?.flexibleLines?.length);
  return [
    new SensorSystem(),
    new ControllerSystem(),
    new PowerSystem(),
    new SignalSystem(),
    new CommandRoutingSystem(),
    new CommandReceiverSystem(),
    new MaterialResourceSystem(),
    new PressureNozzleDemandSystem(),
    new MechanismSystem(),
    new ComponentActuatorSystem(),
    new PneumaticSystem(),
    new ReleaseCouplerSystem(),
    new RollingContactSystem(),
    ...(flexibleLines ? [new FlexibleLineSystem()] : []),
    new EnvironmentBodySystem(),
    new FluidSystem(),
    new PressureNozzleForceSystem(),
    new RotorPropulsionSystem(),
    new AerodynamicSystem(),
    new RigidBodySystem(),
    new MotorEnergySettlementSystem(),
    ...(flexibleLines ? [new FlexibleLineStructureSystem()] : []),
    new StructureSystem(),
    new PneumaticStructureSystem(),
    ...(flexibleLines ? [new FlexibleLineTelemetrySystem()] : []),
    new MaterialResourceCommitSystem(),
    new ThermalSystem(),
    new PneumaticCommitSystem(),
    new MassPropertyCommitSystem(),
    new PhysicalAssemblySystem(),
    new TestSiteTelemetrySystem(),
    new TestCourseSystem(),
    new MobilityTelemetrySystem(),
    new FailureEvidenceSystem(),
    new PhysicalFlightTelemetrySystem(),
    new TelemetrySystem(),
  ];
}

/** Projects completed system telemetry without introducing a UI-only truth. */
export function captureProductionSystemTelemetry(context) {
  const telemetry = context.telemetry;
  return {
    mechanisms: telemetry.mechanisms,
    componentActuators: telemetry.componentActuators,
    releaseCouplers: telemetry.releaseCouplers,
    sensors: telemetry.sensors,
    controllers: telemetry.controllers,
    mobility: telemetry.mobility || null,
    failureEvidence: telemetry.failureEvidence || null,
    articulated: telemetry.articulated || null,
    flight: telemetry.flight || null,
    aerodynamics: telemetry.aerodynamics || null,
    aerothermal: telemetry.aerothermal || null,
    power: telemetry.power,
    motorEnergy: telemetry.motorEnergy || null,
    signals: telemetry.signals,
    commands: telemetry.commands,
    commandReceivers: telemetry.commandReceivers,
    materialResources: telemetry.materialResources,
    pneumatics: telemetry.pneumatics || null,
    propulsion: telemetry.propulsion || null,
    massProperties: telemetry.massProperties || null,
    physicalAssembly: telemetry.physicalAssembly || null,
    testSite: telemetry.testSite || null,
    testCourse: telemetry.testCourse || null,
    environmentBodies: telemetry.environmentBodies || null,
    structures: telemetry.structures,
    integration: telemetry.integration,
    fluids: telemetry.fluids,
    flexibleLines: telemetry.flexibleLines || null,
  };
}
