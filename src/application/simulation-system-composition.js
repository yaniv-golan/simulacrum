/** Projects completed system telemetry without introducing a UI-only truth. */
export function captureProductionSystemTelemetry(context) {
  const telemetry = context.telemetry;
  return {
    mechanisms: telemetry.mechanisms,
    componentActuators: telemetry.componentActuators,
    releaseCouplers: telemetry.releaseCouplers,
    sensors: telemetry.sensors,
    controllers: telemetry.controllers,
    mobility: telemetry.mobility || null,
    articulated: telemetry.articulated || null,
    flight: telemetry.flight || null,
    aerodynamics: telemetry.aerodynamics || null,
    aerothermal: telemetry.aerothermal || null,
    power: telemetry.power,
    signals: telemetry.signals,
    commands: telemetry.commands,
    commandReceivers: telemetry.commandReceivers,
    materialResources: telemetry.materialResources,
    propulsion: telemetry.propulsion || null,
    massProperties: telemetry.massProperties || null,
    physicalAssembly: telemetry.physicalAssembly || null,
    testSite: telemetry.testSite || null,
    testCourse: telemetry.testCourse || null,
    environmentBodies: telemetry.environmentBodies || null,
    structures: telemetry.structures,
    integration: telemetry.integration,
    fluids: telemetry.fluids,
  };
}
