function assemble(id, name, parts, connections) {
  const blueprint = createEmptyBlueprint(id, name);
  blueprint.parts = parts.map(
    ([type, id, position, rotation, authoredMaterial, parameters, springBinding]) => {
      const part = createPart(type, id, [...position]);
      part.name = id
        .split('-')
        .map((word) => word[0].toUpperCase() + word.slice(1))
        .join(' ');
      if (type === 'commandReceiver') {
        part.controlBinding = structuredClone(DEFAULT_CONTROL_BINDING);
        part.controlBinding.drive.gain = 0.2;
      }
      Object.assign(part, {
        rotation: [...rotation],
        authoredMaterial: { ...authoredMaterial },
        parameters: { ...parameters },
      });
      if (springBinding !== null) part.springBinding = springBinding;
      return part;
    },
  );
  blueprint.connections = structuredClone(connections);
  return blueprint;
}
