import crypto from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { componentPartUnionSchema } from "../src/model/component-wire-contract.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schemaDirectory = path.join(root, "src/model/schema");
const generatedDirectory = path.join(root, "src/model/generated");
const targets = Object.freeze([
  ["blueprint", "blueprint-wire-schema.json", "validateBlueprintWire"],
  ["workspace", "workspace-wire-schema.json", "validateWorkspaceWire"],
  ["subassembly", "subassembly-wire-schema.json", "validateSubassemblyWire"],
  [
    "share-package",
    "share-package-wire-schema.json",
    "validateSharePackageWire",
  ],
  ["proof", "proof-wire-schema.json", "validateProofWire"],
  [
    "run-configuration",
    "run-configuration-wire-schema.json",
    "validateRunConfigurationWire",
  ],
  ["input-trace", "input-trace-wire-schema.json", "validateInputTraceWire"],
  ["checkpoint", "checkpoint-wire-schema.json", "validateCheckpointWire"],
  ["experiment", "experiment-wire-schema.json", "validateExperimentWire"],
  [
    "failure-evidence",
    "failure-evidence-wire-schema.json",
    "validateFailureEvidenceWire",
  ],
  [
    "telemetry-playback",
    "telemetry-playback-wire-schema.json",
    "validateTelemetryPlaybackWire",
  ],
  [
    "mechanism-authored-component",
    "mechanism-authored-component-wire-schema.json",
    "validateMechanismAuthoredComponentWire",
  ],
]);
const outputGroups = Object.freeze([
  [
    "portable-machine-wire-validators.js",
    ["blueprint", "workspace", "subassembly", "mechanism-authored-component"],
  ],
  ["share-wire-validators.js", ["share-package", "proof"]],
  [
    "mechanism-artifact-wire-validators.js",
    [
      "run-configuration",
      "input-trace",
      "checkpoint",
      "experiment",
      "telemetry-playback",
      "failure-evidence",
    ],
  ],
]);
const obsoleteOutputs = targets.map(([label]) => `${label}-wire-validator.js`);

const schemaFiles = [
  "common-wire-defs.json",
  "mechanism-artifact-defs.json",
  ...targets.map(([, file]) => file),
];
const sourceEntries = await Promise.all(
  schemaFiles.map(async (file) => [
    file,
    await fs.readFile(path.join(schemaDirectory, file), "utf8"),
  ]),
);
const schemas = new Map(
  sourceEntries.map(([file, source]) => [file, JSON.parse(source)]),
);
const commonSchema = schemas.get("common-wire-defs.json");
commonSchema.$defs.part = componentPartUnionSchema(commonSchema.$defs.part);
const derivedComponentContract = JSON.stringify(commonSchema.$defs.part);
const sourceHash = crypto
  .createHash("sha256")
  .update(
    [
      ...sourceEntries.map(([file, source]) => `${file}\0${source}`),
      `component-catalog-contract\0${derivedComponentContract}`,
    ].join("\0"),
  )
  .digest("hex");

await fs.mkdir(generatedDirectory, { recursive: true });
const checkOnly = process.argv.includes("--check");
for (const obsolete of obsoleteOutputs) {
  const obsoletePath = path.join(generatedDirectory, obsolete),
    exists = await fs
      .access(obsoletePath)
      .then(() => true)
      .catch(() => false);
  if (!exists) continue;
  if (checkOnly)
    throw new Error(
      `Obsolete generated wire validator must be removed: ${path.relative(root, obsoletePath)}`,
    );
  await fs.rm(obsoletePath);
}
for (const [outputFile, labels] of outputGroups) {
  const groupTargets = labels.map((label) => {
    const target = targets.find(([candidate]) => candidate === label);
    if (!target) throw new Error(`Unknown wire-validator target ${label}`);
    return target;
  });
  const ajv = new Ajv2020({
    allErrors: true,
    messages: false,
    code: { source: true, esm: true, optimize: 2 },
    formats: { "date-time": true },
    allowUnionTypes: true,
    discriminator: true,
    loopEnum: 4,
    loopRequired: 4,
    strict: true,
  });
  for (const schema of schemas.values()) ajv.addSchema(schema);
  const exports = {};
  for (const [, file, exportName] of groupTargets) {
    const schemaId = schemas.get(file).$id;
    if (!ajv.getSchema(schemaId)) throw new Error(`Could not compile ${file}`);
    exports[exportName] = schemaId;
  }
  const generated = standaloneCode(ajv, exports)
    .replaceAll(
      'require("ajv/dist/runtime/ucs2length").default',
      "((value) => Array.from(value).length)",
    )
    .replaceAll(
      'require("ajv/dist/runtime/equal").default',
      "((left, right) => JSON.stringify(left) === JSON.stringify(right))",
    );
  const output = [
    "// Generated by scripts/generate-wire-validators.mjs. Do not edit.",
    `// schema-family-sha256: ${sourceHash}`,
    "// @ts-nocheck",
    "/* eslint-disable */",
    generated.trimEnd(),
    "",
  ].join("\n");
  const outputPath = path.join(generatedDirectory, outputFile),
    previous = await fs.readFile(outputPath, "utf8").catch(() => null);
  if (previous === output) continue;
  if (checkOnly)
    throw new Error(
      `Generated wire validator is stale: ${path.relative(root, outputPath)}`,
    );
  await fs.writeFile(outputPath, output, "utf8");
}

process.stdout.write(
  `${checkOnly ? "verified" : "generated"} ${outputGroups.length} wire-validator modules with ${targets.length} exports (${sourceHash.slice(0, 12)})\n`,
);
