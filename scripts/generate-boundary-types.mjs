import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { buildBlueprintSchema } from './generate-schema.mjs';

const target = new URL('../src/model/generated/blueprint-types.d.ts', import.meta.url);
const title = (name) => name[0].toUpperCase() + name.slice(1);

// Only structural guarantees become types. Numeric ranges, uniqueness and
// patterns remain the runtime validator's responsibility. Unsupported structural
// constructs fail generation instead of silently widening the contract.
export function schemaType(schema) {
  if (schema === false) return 'never';
  if (schema.$ref) return title(schema.$ref.split('/').at(-1));
  if (Object.hasOwn(schema, 'const')) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(' | ');
  if (schema.oneOf) {
    const keys = [...new Set(schema.oneOf.flatMap((item) => Object.keys(item.properties ?? {})))];
    return schema.oneOf
      .map((item) =>
        schemaType({
          ...item,
          properties: {
            ...Object.fromEntries(keys.map((key) => [key, false])),
            ...item.properties,
          },
        }),
      )
      .join(' | ');
  }
  if (schema.allOf) throw Error('Resolve conditional part schemas before rendering');
  if (schema.type === 'number' || schema.type === 'integer') return 'number';
  if (schema.type === 'string' || schema.type === 'boolean') return schema.type;
  if (schema.type === 'array') {
    const item = schemaType(schema.items);
    if (schema.minItems === schema.maxItems && Number.isInteger(schema.minItems))
      return `[${Array(schema.minItems).fill(item).join(', ')}]`;
    return `Array<${item}>`;
  }
  if (schema.type === 'object' && schema.additionalProperties === false) {
    if (Object.keys(schema.properties).length === 0) return 'Record<string, never>';
    return `{ ${Object.entries(schema.properties)
      .map(
        ([key, value]) =>
          `${JSON.stringify(key)}${schema.required?.includes(key) ? '' : '?'}: ${schemaType(value)}`,
      )
      .join('; ')} }`;
  }
  throw Error(`Unsupported structural schema: ${JSON.stringify(schema)}`);
}

export function boundaryTypes() {
  const schema = buildBlueprintSchema();
  const part = schema.$defs.part;
  const variants = part.allOf.map(({ if: condition, then }) =>
    schemaType({
      ...part,
      allOf: undefined,
      properties: {
        ...part.properties,
        ...then.properties,
        type: condition.properties.type,
      },
    }),
  );
  return (
    '// Generated by scripts/generate-boundary-types.mjs from the runtime schema and catalog.\n' +
    Object.entries(schema.$defs)
      .map(
        ([key, definition]) =>
          `export type ${title(key)} = ${key === 'part' ? variants.join(' | ') : schemaType(definition)};\n`,
      )
      .join('') +
    `export type Blueprint = ${schemaType(schema)};\n` +
    "export type PartType = Part['type'];\nexport type MaterialKey = NonNullable<Part['authoredMaterial']['body']>;\n"
  );
}
export function generateBoundaryTypes({ check = false, destination = target } = {}) {
  const output = boundaryTypes();
  if (check) {
    if (readFileSync(destination, 'utf8') !== output)
      throw Error('Boundary types are stale; run node scripts/generate-boundary-types.mjs');
  } else writeFileSync(destination, output);
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href)
  generateBoundaryTypes({ check: process.argv.includes('--check') });
